"""Source-bound saved-structure window gate; pixel checks are not visual acceptance."""
import hashlib
import math
import stat
import zlib
from pathlib import Path

from documents_window_gate import identifier, number
from source_stream_gate import decode, digest, integer
from source_stream_window_gate import _png

CHECKS = tuple("structure-" + key for key in (
    "clean-open-preserves-state", "all-tabs-accessible", "json-readonly", "minimum-window-captured",
    "clean-close-preserves-state", "dirty-open-preserves-state", "dirty-source-report-stable",
    "dirty-close-preserves-history", "undo-restores-project", "large-multipage-complete",
    "large-json-end-accessible", "json-window-captured", "large-close-preserves-state", "source-files-unchanged"))
TABS = ("Overview", "Hierarchy", "Tracks", "Issues", "Complete JSON")
CAPTURES = ("native-project-structure-minimum-visual.png", "native-project-structure-json-visual.png")
PAYLOADS = ("Project.json", "Compatibility/CPR/Original.cpr", "Compatibility/CPR/ImportReport.json")
INPUT = "Actual Project menu, tab, read-only value, gain, undo and Close UIA callbacks; WPF ScrollToEnd. No physical input."
SCOPE = "Preserved source only; later project edits are not represented. Saved Volume and bus values are raw candidates, not application gain or effective routing. Runtime processing remains unresolved."
GENERATOR_FILES = ("CPRNativeProjectBindingsTests.swift", "CPRProjectStructureSnapshotTests.swift")
COUNTS = ("entries", "tracks", "issues", "lists", "nativeObjects", "resourceAssociations")
STATE = {"state_sha256", "project_sha256", "revision", "dirty", "needs_save_as", "can_undo", "can_redo", "track_id", "clip_id"}


def require(ok, message):
    if not ok:
        raise ValueError("Structure window: " + message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def keys(value, names, message):
    require(isinstance(value, dict) and set(value) == set(names), message)


def regular(path, maximum):
    info = path.lstat()
    require(stat.S_ISREG(info.st_mode) and not path.is_symlink() and
            not getattr(info, "st_file_attributes", 0) & 0x400 and 0 < info.st_size <= maximum,
            "fixture is not a bounded regular file")
    return path.read_bytes()


def require_structure_fixture(root, generator_hashes=None):
    """Verify generated bytes independently before the native journey and after it."""
    root = Path(root)
    raw = regular(root / "expected.json", 65536)
    expected = decode(raw)
    keys(expected, ("schema", "evidenceClass", "scope", "generatorSHA256", "cases"), "fixture envelope differs")
    require(expected["schema"] == "rebase.project-structure-fixtures.v1" and
            expected["evidenceClass"] == "authored-synthetic-control" and isinstance(expected["scope"], str) and
            "No reference execution" in expected["scope"], "fixture provenance differs")
    keys(expected["generatorSHA256"], GENERATOR_FILES, "missing generator source bindings")
    require(all(digest(v) for v in expected["generatorSHA256"].values()), "invalid generator hashes")
    if generator_hashes is not None:
        require(expected["generatorSHA256"] == generator_hashes, "generator source differs")
    cases = expected["cases"]
    require(isinstance(cases, list) and len(cases) == 2, "fixture case count differs")
    inventory = {"expected.json": sha(raw)}
    for index, (name, stem) in enumerate((("small", "Small"), ("large", "Large"))):
        case = cases[index]
        keys(case, ("name", "root", "projectID", "trackID", "sourceSHA256", "sourceBytes", "reportSHA256",
                    "reportBytes", "reportFile", "manifestSHA256", "counts", "files"), "fixture case keys differ")
        require(case["name"] == name and case["root"] == stem + ".rebaseproj" and case["reportFile"] == stem + ".structure.json" and
                identifier(case["projectID"]) and identifier(case["trackID"]), "fixture identity differs")
        keys(case["counts"], COUNTS, "fixture section count keys differ")
        require(all(integer(v, 0, 1000000) for v in case["counts"].values()), "invalid fixture section count")
        files = case["files"]
        require(isinstance(files, list) and len(files) == 3, "fixture file count differs")
        payload = {}
        for item, relative in zip(files, PAYLOADS):
            keys(item, ("path", "bytes", "sha256"), "fixture file keys differ")
            require(item["path"] == relative and integer(item["bytes"], 1, 8 * 1024 * 1024) and digest(item["sha256"]), "fixture file lock differs")
            path = case["root"] + "/" + relative
            data = regular(root / path, 8 * 1024 * 1024)
            require(len(data) == item["bytes"] and sha(data) == item["sha256"], "fixture payload differs")
            inventory[path] = sha(data); payload[relative] = data
        require(case["sourceSHA256"] == sha(payload[PAYLOADS[1]]) and
                integer(case["sourceBytes"], len(payload[PAYLOADS[1]]), len(payload[PAYLOADS[1]])) and
                case["manifestSHA256"] == sha(payload[PAYLOADS[0]]), "fixture source/manifest binding differs")
        project = decode(payload["Project.json"])
        require(project.get("id", "").lower() == case["projectID"].lower() and len(project.get("tracks", [])) == 1 and
                project["tracks"][0].get("id", "").lower() == case["trackID"].lower() and
                project["tracks"][0].get("clips") == [], "fixture application selection differs")
        report_bytes = regular(root / case["reportFile"], 8 * 1024 * 1024)
        require(sha(report_bytes) == case["reportSHA256"] and integer(case["reportBytes"], len(report_bytes), len(report_bytes)) and
                (0 < len(report_bytes) < 65536 if index == 0 else 65536 < len(report_bytes) < 262144), "fixture report bound differs")
        report = decode(report_bytes)
        require(report.get("schemaVersion") == 1 and report.get("sourceSHA256") == case["sourceSHA256"] and
                integer(report.get("sourceByteCount"), case["sourceBytes"], case["sourceBytes"]) and
                all(isinstance(report.get(key), list) and len(report[key]) == case["counts"][key] for key in COUNTS),
                "complete report identity or section counts differ")
        inventory[case["reportFile"]] = sha(report_bytes)
    actual = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file() or p.is_symlink()}
    require(actual == set(inventory), "unexpected or missing fixture file")
    return expected, sha(raw), inventory


def state(value, expected, revision, dirty, undo, redo):
    keys(value, STATE, "state keys differ")
    require(all(digest(value[key]) for key in ("state_sha256", "project_sha256")) and
            integer(value["revision"], revision, revision) and value["dirty"] is dirty and
            value["needs_save_as"] is False and value["can_undo"] is undo and value["can_redo"] is redo and
            isinstance(value["track_id"], str) and value["track_id"].lower() == expected["trackID"].lower() and
            value["clip_id"] is None, "state, history or selection differs")


def capture(value, file, section, expected, evidence):
    keys(value, ("file", "sha256", "alpha_coverage", "bounds", "controls", "selected_section", "scope",
                 "report_sha256", "report_bytes", "frame_excluded"), "capture fields differ")
    require(value["file"] == file and value["selected_section"] == section and value["scope"] == SCOPE and
            value["frame_excluded"] is True and value["report_sha256"] == expected["reportSHA256"] and
            integer(value["report_bytes"], expected["reportBytes"], expected["reportBytes"]), "capture provenance differs")
    b = value["bounds"]
    keys(b, ("outer_width_dip", "outer_height_dip", "width_dip", "height_dip", "dpi_scale_x", "dpi_scale_y", "pixel_width", "pixel_height"), "capture bounds keys differ")
    for dimension, axis, minimum, outer in (("width", "x", 600, 660), ("height", "y", 380, 480)):
        require(number(b[dimension + "_dip"], minimum, outer + .5) and number(b["outer_" + dimension + "_dip"], outer - .5, outer + .5) and
                b[dimension + "_dip"] <= b["outer_" + dimension + "_dip"] and number(b["dpi_scale_" + axis], .5, 4), "minimum capture bounds differ")
        n = math.ceil(b[dimension + "_dip"] * b["dpi_scale_" + axis])
        require(integer(b["pixel_" + dimension], n, n), "capture DPI/pixels differ")
    controls = value["controls"]; names = ("sections", "content", "close", *("tab-" + t for t in TABS))
    require(isinstance(controls, list) and len(controls) == len(names), "missing visible controls")
    for row, name in zip(controls, names):
        keys(row, ("name", "x", "y", "width", "height", "visible", "enabled"), "control fields differ")
        require(row["name"] == name and row["visible"] is True and row["enabled"] is True and
                all(number(row[k], -.5 if k in ("x", "y") else 1, 4096) for k in ("x", "y", "width", "height")) and
                row["x"] + row["width"] <= b["width_dip"] + .5 and row["y"] + row["height"] <= b["height_dip"] + .5,
                "control is hidden, disabled, clipped or misidentified")
    sections, content, close = controls[:3]
    require(content["x"] >= sections["x"] - .5 and content["y"] >= sections["y"] - .5 and
            content["x"] + content["width"] <= sections["x"] + sections["width"] + .5 and
            content["y"] + content["height"] <= sections["y"] + sections["height"] + .5 and
            content["width"] >= 450 and content["height"] >= 100 and close["width"] >= 80 and close["height"] >= 20 and
            close["y"] >= sections["y"] + sections["height"] - .5, "report viewport/footer is unusable")
    image = _png(Path(evidence) / file, value["sha256"], b, value["alpha_coverage"])
    image["file"] = file
    return image


def require_structure_window(smoke, evidence, fixture_root, expected_helper_sha256, generator_hashes=None):
    try:
        expected, fixture_hash, inventory = require_structure_fixture(fixture_root, generator_hashes)
        require(isinstance(smoke, dict) and smoke.get("outcome") == "passed", "native journey did not pass")
        checks = smoke["checks"]
        require(isinstance(checks, list) and all(isinstance(v, str) for v in checks) and len(checks) == len(set(checks)) and
                tuple(v for v in checks if v.startswith("structure-")) == CHECKS, "missing, duplicated or reordered native checks")
        r = smoke["project_structure"]
        keys(r, ("tested", "fixture_sha256", "cases", "captures", "custody", "after_undo", "helper_sha256",
                 "physical_input_tested", "native_file_pickers_tested", "playback_tested", "input_evidence"), "receipt keys differ")
        require(r["tested"] is True and digest(expected_helper_sha256) and r["helper_sha256"] == expected_helper_sha256 and
                r["fixture_sha256"] == fixture_hash and r["input_evidence"] == INPUT and all(r[k] is False for k in
                ("physical_input_tested", "native_file_pickers_tested", "playback_tested")), "unsupported claim or unbound helper/fixture")
        rows = r["cases"]
        require(isinstance(rows, list) and len(rows) == 3, "missing inspected phase")
        base = rows[0]["before"]["revision"]
        require(integer(base, 1, (1 << 64) - 4), "invalid base revision")
        for row, name, lock, delta in zip(rows, ("clean", "dirty", "large"), (expected["cases"][0], expected["cases"][0], expected["cases"][1]), (0, 1, 3)):
            fields = {"name", "before", "opened", "after", "commands", "page_count", "snapshot", "report_sha256", "report_bytes"}
            fields |= {"visited_sections", "read_only"} if name == "clean" else {"scroll"} if name == "large" else set()
            keys(row, fields, "phase fields differ")
            require(row["name"] == name and row["report_sha256"] == lock["reportSHA256"] and
                    integer(row["report_bytes"], lock["reportBytes"], lock["reportBytes"]), "phase report differs")
            for phase in ("before", "opened", "after"):
                state(row[phase], lock, base + delta, name == "dirty", name == "dirty", False)
            require(row["before"] == row["opened"] == row["after"], "inspection or close mutates session")
            pages = (lock["reportBytes"] + 65535) // 65536
            require(integer(row["page_count"], pages, pages), "page count differs")
            keys(row["commands"], ("inspectProjectStructure", "projectStructurePage", "closeProjectStructure"), "command fields differ")
            require(all(integer(row["commands"][key], count, count) for key, count in
                (("inspectProjectStructure", 1), ("projectStructurePage", pages - 1), ("closeProjectStructure", 1))), "page/cleanup request count differs")
            s = row["snapshot"]
            binding = {"project_id": lock["projectID"], "revision": base + delta, "source_sha256": lock["sourceSHA256"], "source_bytes": lock["sourceBytes"],
                       "manifest_sha256": lock["manifestSHA256"], "report_sha256": lock["reportSHA256"], "report_bytes": lock["reportBytes"],
                       **{k: lock["counts"][k] for k in ("entries", "tracks", "issues", "lists")},
                       "native_objects": lock["counts"]["nativeObjects"], "resource_associations": lock["counts"]["resourceAssociations"]}
            keys(s, binding, "snapshot fields differ")
            require(all((integer(s[k], v, v) if type(v) is int else isinstance(s[k], str) and s[k].lower() == v.lower())
                        for k, v in binding.items()), "complete snapshot differs from source/report lock")
        clean, dirty, large = rows
        require(clean["visited_sections"] == list(TABS), "not every report section was visited")
        ro = clean["read_only"]; keys(ro, ("is_read_only", "provider_read_only", "write_rejected", "before_sha256", "after_sha256"), "readonly fields differ")
        require(all(ro[k] is True for k in ("is_read_only", "provider_read_only", "write_rejected")) and
                ro["before_sha256"] == ro["after_sha256"] == clean["report_sha256"], "JSON mutation was permitted")
        state(r["after_undo"], expected["cases"][0], base + 2, False, False, True)
        require(r["after_undo"]["project_sha256"] == clean["before"]["project_sha256"] and
                len({row["before"]["project_sha256"] for row in rows}) == 3 and
                len({row["before"]["state_sha256"] for row in rows} | {r["after_undo"]["state_sha256"]}) == 4, "edit/Undo transition is not bound")
        scroll = large["scroll"]
        keys(scroll, ("before_offset", "after_offset", "viewport_height", "extent_height", "first_visible_line", "last_visible_line", "last_source_line", "json_sha256", "json_bytes", "read_only"), "scroll fields differ")
        require(scroll["read_only"] is True and scroll["json_sha256"] == large["report_sha256"] and
                integer(scroll["json_bytes"], large["report_bytes"], large["report_bytes"]) and
                all(number(scroll[k], 0, 10000000) for k in ("before_offset", "after_offset", "viewport_height", "extent_height")) and
                scroll["viewport_height"] >= 80 and scroll["extent_height"] > scroll["viewport_height"] and
                scroll["after_offset"] > scroll["before_offset"] and
                abs(scroll["after_offset"] + scroll["viewport_height"] - scroll["extent_height"]) <= 1 and
                all(integer(scroll[k], 0, 1000000) for k in ("first_visible_line", "last_visible_line", "last_source_line")) and
                scroll["first_visible_line"] <= scroll["last_visible_line"] and scroll["last_visible_line"] >= scroll["last_source_line"], "complete JSON end is not accessible")
        custody = r["custody"]
        require(isinstance(custody, list) and len(custody) == 6, "custody inventory differs")
        for row, (lock, item) in zip(custody, ((case, item) for case in expected["cases"] for item in case["files"])):
            keys(row, ("name", "path", "bytes", "original_sha256", "copy_sha256"), "custody fields differ")
            require(row["name"] == lock["name"] and row["path"] == item["path"] and integer(row["bytes"], item["bytes"], item["bytes"]) and
                    row["original_sha256"] == row["copy_sha256"] == item["sha256"], "source or working copy changed")
        require(isinstance(r["captures"], list) and len(r["captures"]) == 2, "capture count differs")
        images = [capture(v, f, section, lock, evidence) for v, f, section, lock in
                  zip(r["captures"], CAPTURES, ("Tracks", "Complete JSON"), expected["cases"])]
        return {"schema": "rebase.structure-window-summary.v1", "native_checks": len(CHECKS), "helper_sha256": expected_helper_sha256,
                "fixture_sha256": fixture_hash, "fixture_files": len(inventory), "phases": 3, "page_counts": [r["page_count"] for r in rows],
                "report_sha256": [case["reportSHA256"] for case in expected["cases"]], "captures": images,
                "complete_report_bound": True, "source_custody_bound": True, "physical_input_tested": False,
                "native_file_pickers_tested": False, "playback_tested": False, "visual_acceptance_claimed": False}
    except (KeyError, TypeError, AttributeError, IndexError, UnicodeError, OSError, zlib.error, OverflowError, RecursionError) as error:
        raise ValueError("Structure window: malformed or missing evidence") from error
