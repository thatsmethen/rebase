final class NativeTempoClockTests {
    private func clock(_ bits: UInt32 = 0x42fd0000) throws -> NativeTempoClock {
        try NativeTempoClock(fixedBPMBits: bits, sourceSHA256: String(repeating: "a", count: 64), sourceObjectOffset: 758)
    }
    private func map() throws -> TempoMap {
        let clock = try clock()
        return TempoMap(events: [TempoEvent(beat: 0, bpm: clock.fixedBPM)], nativeClock: clock)
    }
    private func workspace<T>(_ body: (URL) throws -> T) throws -> T {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("NativeClockTests-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        return try body(root)
    }

    @Test func fixedOperationsMatchIndependentRationalBitVectors() throws {
        // Exact rational IEEE rounding, one operation at a time, independently
        // generated by APP004/native-clock-oracle.py. These are analytical
        // controls, not captures from executing the proprietary application.
        let vectors: [(UInt32, UInt32, UInt64, UInt64, UInt64, UInt64)] = [
            (0x42fd0000, 0x3ef2d88a, 0x40c81cd6e63c53b2, 0x402866090b368ace, 0x405edd3c07fb4c69, 0x40fe80a4476ed32c),
            (0x42fd0001, 0x3ef2d889, 0x425bf08eafffe000, 0x41bc455eba22ec9f, 0x40f5180000000000, 0x4194d8b80d76a188),
            (0x42b80000, 0x3f26f4df, 0x407e000000000000, 0x3fe4de9be0000000, 0x3ff0000000000000, 0x4086fffff233333c),
            (0x428c0000, 0x3f5b6db7, 0x4121940000000000, 0x4090124927400000, 0x4082c00000000000, 0x411481fffc950000),
            (0x42820000, 0x3f6c4ec5, 0x3fc0000000000000, 0x3f2f81f822222222, 0x3fc0000000000000, 0x40503ffffea55555),
            (0x41a00000, 0x40400000, 0x407e000000000000, 0x4008000000000000, 0x4008000000000000, 0x407e000000000000),
            (0x43c80000, 0x3e19999a, 0x407e000000000000, 0x3fc3333340000000, 0x3fc3333333333333, 0x407dffffec00000d)]
        for (bpm, period, tick, expectedSeconds, seconds, expectedTick) in vectors {
            let c = try clock(bpm)
            #expect(try c.periodBits() == period)
            #expect(try c.seconds(atNativeTick: Double(bitPattern: tick)).bitPattern == expectedSeconds)
            #expect(try c.nativeTick(atSeconds: Double(bitPattern: seconds)).bitPattern == expectedTick)
        }
        let c = try clock()
        #expect(try c.seconds(atNativeTick: 0).bitPattern == 0)
        #expect(try c.nativeTick(atSeconds: 0).bitPattern == 0)
        #expect(try c.seconds(atNativeTick: 480) != 60 / c.fixedBPM)
    }

    @Test func descriptorRoundTripAndMalformedInputsReject() throws {
        let c = try clock()
        let encoded = try JSONEncoder().encode(c)
        #expect(try JSONDecoder().decode(NativeTempoClock.self, from: encoded) == c)
        let original = try #require(JSONSerialization.jsonObject(with: encoded) as? [String: Any])
        for (key, value): (String, Any) in [("contract", "unknown"), ("fixedBPMBits", UInt32(0x7fc00000)),
            ("fixedBPMBits", Float(19).bitPattern), ("fixedBPMBits", UInt64(UInt32.max) + 1),
            ("sourceSHA256", "abc"), ("sourceObjectOffset", -1),
            ("sourceObjectOffset", CPRProject.maximumFileBytes), ("interpretationProfile", "unknown")] {
            var changed = original; changed[key] = value
            expectThrows(try JSONDecoder().decode(NativeTempoClock.self, from: JSONSerialization.data(withJSONObject: changed)))
        }
        for key in original.keys {
            var changed = original; changed.removeValue(forKey: key)
            expectThrows(try JSONDecoder().decode(NativeTempoClock.self, from: JSONSerialization.data(withJSONObject: changed)))
        }
        for bad in [Double.nan, .infinity, -1, Double.leastNonzeroMagnitude] {
            expectThrows(try c.seconds(atNativeTick: bad))
            expectThrows(try c.nativeTick(atSeconds: bad))
        }
        expectThrows(try c.seconds(atNativeTick: TempoMap.maximumBeat * 480 + 1))
        expectThrows(try c.nativeTick(atSeconds: Double.greatestFiniteMagnitude))
    }

    @Test(.enabled(if: PrivateResearchFixtures.isConfigured, PrivateResearchFixtures.reason))
    func reviewerOracleCoversMantissaAndOperationOrderDiscriminators() throws {
        let bytes = try Data(contentsOf: independentClockVectors)
        let hash = SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
        #expect(hash == "bc9d7eef520a3c82e1941ff3e37b48d07dc9dc09a21642db058062cc97221a02")
        let document = try #require(JSONSerialization.jsonObject(with: bytes) as? [String: Any])
        let vectors = try #require(document["vectors"] as? [[String: String]])
        #expect(vectors.count == 36)
        func bits(_ vector: [String: String], _ key: String) throws -> UInt64 {
            let text = try #require(vector[key])
            return try #require(UInt64(text.dropFirst(2), radix: 16))
        }
        var discriminators = 0
        for vector in vectors {
            let c = try clock(UInt32(try bits(vector, "bpm_f32_bits")))
            let input = Double(bitPattern: try bits(vector, "input_f64_bits"))
            let expected = try bits(vector, "result_f64_bits")
            #expect(try c.periodBits() == UInt32(bits(vector, "period_f32_bits")))
            switch vector["direction"] {
            case "ticks_to_seconds": #expect(try c.seconds(atNativeTick: input).bitPattern == expected)
            case "seconds_to_ticks": #expect(try c.nativeTick(atSeconds: input).bitPattern == expected)
            default: Issue.record("Unknown analytical direction")
            }
            if try bits(vector, "reordered_result_f64_bits") != expected { discriminators += 1 }
        }
        #expect(discriminators == 7)
    }

    @Test func nonNearestRoundingEnvironmentIsRejectedWithoutChangingIt() throws {
        let c = try clock()
        let original = fegetround()
        defer { _ = fesetround(original) }
        #expect(fesetround(FE_UPWARD) == 0)
        expectThrows(try c.periodBits())
        expectThrows(try c.seconds(atNativeTick: 480))
        #expect(fegetround() == FE_UPWARD)
    }

    @Test func tempoMapUsesNativeArithmeticAndRejectsInconsistentProjection() throws {
        let native = try map(), c = try #require(native.nativeClock)
        let beat = 12345.6789012345 / 480
        #expect(try native.seconds(atBeat: beat).bitPattern == c.seconds(atNativeTick: beat * 480).bitPattern)
        #expect(try native.beat(atSeconds: 123.456789012345).bitPattern == (c.nativeTick(atSeconds: 123.456789012345) / 480).bitPattern)
        #expect(try JSONDecoder().decode(TempoMap.self, from: JSONEncoder().encode(native)) == native)
        var changed = native; changed.events[0].bpm = 127
        expectThrows(try changed.validate())
        changed = native; changed.events.append(TempoEvent(beat: 4, bpm: 126.5))
        expectThrows(try changed.validate())
        let application = try native.convertedToApplicationTiming()
        #expect(application.nativeClock == nil && application.events == native.events)
        #expect(try native.seconds(atBeat: 1) != application.seconds(atBeat: 1))
        let legacy = try JSONDecoder().decode(TempoMap.self, from: JSONEncoder().encode(application))
        #expect(legacy.nativeClock == nil && legacy == application)
    }

    @Test func explicitProjectConversionRetainsMusicalAnchorsAtomically() throws {
        let tempo = try map()
        let clip = Clip(mediaPath: "Media/fixture.wav", name: "Musical", position: try tempo.seconds(atBeat: 1234),
                        duration: 1, timeBase: .musical, musicalPosition: 1234)
        var project = Project(tracks: [Track(name: "Track", clips: [clip], timeBase: .musical)], tempoMap: tempo)
        try project.validate()
        let original = project
        expectThrows(try project.replaceTempoMap(TempoMap(events: tempo.events)))
        #expect(project == original)
        try project.replaceTempoMap(tempo)
        #expect(project == original)
        try project.convertToApplicationTiming()
        #expect(project.tempoMap.nativeClock == nil)
        #expect(project.tracks[0].clips[0].musicalPosition == 1234)
        #expect(try project.tracks[0].clips[0].position == project.tempoMap.seconds(atBeat: 1234))
        #expect(project.tracks[0].clips[0].position != original.tracks[0].clips[0].position)
        try project.validate()
    }

    @Test func dawprojectExportRequiresExplicitClockConversion() throws {
        try workspace { root in
            var project = Project(tempoMap: try map())
            let output = root.appendingPathComponent("Clock.dawproject")
            expectThrows(try DAWProject.export(project: project, projectRoot: root, to: output))
            #expect(!FileManager.default.fileExists(atPath: output.path))
            try project.convertToApplicationTiming()
            try DAWProject.export(project: project, projectRoot: root, to: output)
            #expect(FileManager.default.fileExists(atPath: output.path))
        }
    }
}
