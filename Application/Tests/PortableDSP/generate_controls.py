#!/usr/bin/env python3
"""Project published independent oracle values into numeric-only C fixtures.

No candidate binary or candidate arithmetic is executed. This script performs
only field selection and serialization. --check verifies the committed fixture
and provenance manifest without changing them.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SOURCES = {
    "seek": "research/evidence/application/APP016/accessor-state-oracle.json",
    "pcm24": "research/evidence/application/APP016/accessor-pcm24-oracle-v2.json",
    "callback": "research/evidence/application/APP013/callback-adapter-oracle.json",
    "reader": "research/evidence/application/APP014/timeline-reader-oracle.json",
    "builder": "research/evidence/cubase-static/cpr-audio-events-001/placed-event-builder/validation/APP015/placed-source-oracle.json",
    "overlap": "research/evidence/cubase-static/cpr-audio-events-001/track-overlaps/branch-controls.json",
    "gain": "research/evidence/cubase-static/cpr-audio-events-001/accessor-gain-order/validation/gain-order-stage-oracle.json",
}

def u32(value):
    return f"UINT32_C(0x{int(value, 16):08x})"

def u64(value):
    return f"UINT64_C(0x{int(value, 16):016x})"

def i64(value):
    if value == -(1 << 63):
        return "INT64_MIN"
    return ("-" if value < 0 else "") + f"INT64_C({abs(value)})"

def row(items):
    return "{" + ",".join(str(x) for x in items) + "}"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    documents, provenance = {}, []
    for name, path in SOURCES.items():
        data = (ROOT / path).read_bytes()
        documents[name] = json.loads(data)
        provenance.append({"name": name, "path": path, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
    lines = ["/* Generated by generate_controls.py; independent authored analytical values.",
             "   No proprietary target execution and no candidate-derived expectations. */",
             "#ifndef REBASE_PORTABLE_DSP_CONTROLS_H", "#define REBASE_PORTABLE_DSP_CONTROLS_H", "#include <stdint.h>"]
    counts = {}
    def array(name, declaration, values):
        lines.append("typedef struct { " + declaration + " } " + name + "_row;")
        lines.append("static const " + name + "_row " + name + "[] = {")
        lines.extend("    " + value + "," for value in values)
        lines.append("};")
        counts[name] = len(values)

    seek = documents["seek"]["seek_vectors"]
    array("seek_controls", "uint32_t source, output; int64_t requested, source_frame, returned; uint32_t ratio; uint64_t product, quotient;",
          [row([u32(struct.pack(">f", r["source_rate"]).hex()), u32(struct.pack(">f", r["output_rate"]).hex()),
                i64(r["requested_frame"]), i64(r["source_frame"]), i64(r["returned_frame"]),
                u32(r["ratio_bits"]), u64(r["source_product_bits"]), u64(r["quotient_bits"])]) for r in seek])
    pcm = documents["pcm24"]["vectors"]
    array("pcm24_controls", "uint32_t input, output; int accepted;",
          [row([u32(r["input_f32_bits"]), u32(r.get("output_f32_bits", "0")), int(r["accepted"])]) for r in pcm])
    gain = documents["gain"]["equal_rate_vectors"]
    array("gain_controls", "uint32_t input, gain, output;",
          [row([u32(r["decoded_bits"]), u32(r["gain_bits"]), u32(r["separate_bits"])]) for r in gain])
    callback = documents["callback"]
    array("callback_windows", "int64_t position; uint64_t offset, rate; int32_t frames; int valid; int64_t start, end;",
          [row([i64(r["position"]), u64(r["offset_bits"]), u64(r["rate_bits"]), r["frames"], int(r["valid"]),
                i64(r["start"] if r["valid"] else 0), i64(r["end"] if r["valid"] else 0)]) for r in callback["windows"]])
    array("callback_offsets", "int32_t frames; uint64_t rate, output;",
          [row([r["frames"], u64(r["rate_bits"]), u64(r["expected_bits"])]) for r in callback["offsets"]])
    array("callback_prefixes", "int64_t start, end, boundary; int32_t transport, expected; uint8_t whole;",
          [row([i64(r["start"]), i64(r["end"]), i64(r["boundary"]), r["transport"], r["expected"], r["whole"]]) for r in callback["prefixes"]])
    capacity = max(r["capacity"] for r in callback["postprocess"])
    channels = max(len(r["input_bits"]) for r in callback["postprocess"])
    lines += [f"#define CONTROL_CALLBACK_CAPACITY {capacity}", f"#define CONTROL_CALLBACK_CHANNELS {channels}"]
    array("callback_samples", f"int32_t frames, capacity, offset, prefix, channels, valid, action; uint32_t input[{channels}][{capacity}], output[{channels}][{capacity}];",
          [row([r["frames"], r["capacity"], r["offset"], r["prefix"], len(r["input_bits"]), int(r["valid"]), r["action"],
                row([row([u32(x) for x in c]) for c in r["input_bits"]]),
                row([row([u32(x) for x in c]) for c in (r.get("output_bits") or r["input_bits"])])]) for r in callback["postprocess"]])
    reader = documents["reader"]
    array("reader_quantizers", "uint64_t period, coordinate; int valid; int64_t expected;",
          [row([u64(r["period_bits"]), u64(r["coordinate_bits"]), int(r["signed64_representable"]),
                i64(r["expected"] if r["signed64_representable"] else 0)]) for r in reader["quantizers"]])
    array("reader_partitions", "uint64_t start, end; int32_t remaining; uint32_t flags; int64_t expected_start, expected_end, frames; int silence;",
          [row([u64(r["start_bits"]), u64(r["end_bits"]), r["remaining"], r["flags"], i64(r["start"]), i64(r["end"]), i64(r["frames"]), int(r["silence"])]) for r in reader["partitions"]])
    array("reader_results", "int32_t request; int64_t begin, segment; uint32_t retried; int32_t returned, action, native_result;",
          [row([r["request"], i64(r["begin"]), i64(r["segment"]), r["retried"], r["returned"], r["action"], r["native"]]) for r in reader["reads"]])
    builder = documents["builder"]["builder_vectors"] + documents["builder"]["source_vectors"]
    inputs = ["event_start_bits", "event_end_bits", "context_offset_bits", "window_start_bits", "window_end_bits", "rate_bits"]
    outputs = ["period_bits", "clipped_start_bits", "clipped_end_bits", "clipped_offset_bits", "start_bits", "reconstructed_end_bits", "length_bits", "offset_bits", "getter_end_bits"]
    array("builder_controls", "uint64_t input[6], output[9]; int64_t start, end, offset; int disposition, empty_reason;",
          [row([row([u64(r[k]) for k in inputs]), row([u64(r.get(k, "0")) for k in outputs]), i64(r.get("start_frame", 0)), i64(r.get("end_frame", 0)),
                i64(r.get("offset_frame", 0)), r["disposition"], r["empty_reason"]]) for r in builder])
    overlap = documents["overlap"]["controls"]
    max_in = max(len(r["input"]) for r in overlap)
    max_out = max(len(r["output"]) for r in overlap)
    lines += [f"#define CONTROL_OVERLAP_INPUTS {max_in}", f"#define CONTROL_OVERLAP_OUTPUTS {max_out}",
              "typedef struct { int32_t index, ordinal, priority; uint64_t start, end; } overlap_range;"]
    def ranges(values):
        return row([row([r["event"], r["ordinal"], r["priority"], u64(r["start_bits"]), u64(r["end_bits"])]) for r in values])
    array("overlap_controls", f"int32_t inputs, outputs; overlap_range input[{max_in}], output[{max_out}];",
          [row([len(r["input"]), len(r["output"]), ranges(r["input"]), ranges(r["output"])]) for r in overlap])
    lines.append("#endif")
    header = ("\n".join(lines) + "\n").encode()
    manifest = {"schema": "rebase-portable-dsp-controls-v1", "target_execution_count": 0,
                "expected_values_from_candidate": False, "sources": provenance, "counts": counts,
                "controls_header_sha256": hashlib.sha256(header).hexdigest(),
                "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    manifest_data = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    for name, data in [("controls.h", header), ("controls-manifest.json", manifest_data)]:
        path = HERE / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Committed portable controls differ: {name}")
        else:
            path.write_bytes(data)
    print(json.dumps({"verified": args.check, "counts": counts, "header_sha256": manifest["controls_header_sha256"]}, sort_keys=True))

if __name__ == "__main__":
    main()
